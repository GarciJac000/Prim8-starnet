'use strict';
/* node dev/cli-logo-image.cjs — store the REAL StarNet wordmark for the terminal: website/assets/starnet-logo-glow.png
   (the master outlined wordmark with its glow), trimmed to the mark, reduced to one 8-bit light channel (how much of the
   logo's light falls on each pixel: alpha × brightness), scaled to an 800-px-wide master and deflated into
   bin/lib/logo-image.js. bin/lib/sixel.js scales that master to the terminal's own cells at run time and draws it as a
   Sixel image, so a terminal that draws images shows the exact logo. Needs the dev dependency sharp. */
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const sharp = require('sharp');

const REPO = path.resolve(__dirname, '..');
const SRC = path.join(REPO, 'website', 'assets', 'starnet-logo-glow.png');
const WIDTH = 800;

(async () => {
  const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height;
  const light = new Uint8Array(W * H);
  for (let i = 0; i < W * H; i++) {
    const r = data[i * 4], g = data[i * 4 + 1], b = data[i * 4 + 2], a = data[i * 4 + 3];
    light[i] = Math.round(Math.max(r, g, b) * a / 255);   // the glow keeps its falloff; the transparent margin is 0
  }
  let x0 = W, y0 = H, x1 = -1, y1 = -1;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (light[y * W + x] > 24) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const pad = 2;
  x0 = Math.max(0, x0 - pad); y0 = Math.max(0, y0 - pad); x1 = Math.min(W - 1, x1 + pad); y1 = Math.min(H - 1, y1 + pad);
  const cw = x1 - x0 + 1, ch = y1 - y0 + 1;
  const h = Math.round(WIDTH * ch / cw);
  const master = await sharp(Buffer.from(light), { raw: { width: W, height: H, channels: 1 } })
    .extract({ left: x0, top: y0, width: cw, height: ch })
    .resize(WIDTH, h, { kernel: 'lanczos3' })
    .extractChannel(0).raw().toBuffer();   // sharp hands a one-channel input back as three: keep one
  if (master.length !== WIDTH * h) throw new Error('master is ' + master.length + ' bytes, expected ' + WIDTH * h);
  const packed = zlib.deflateSync(master, { level: 9 }).toString('base64');
  const body = '/* bin/lib/logo-image.js — GENERATED by dev/cli-logo-image.cjs from website/assets/starnet-logo-glow.png (the real\n'
    + '   wordmark). One 8-bit light channel, ' + WIDTH + '×' + h + ', deflated + base64. Never edit by hand: regenerate. */\n'
    + "'use strict';\nmodule.exports = { width: " + WIDTH + ', height: ' + h + ", light: '" + packed + "' };\n";
  fs.writeFileSync(path.join(REPO, 'bin', 'lib', 'logo-image.js'), body);
  console.log('wrote bin/lib/logo-image.js · master ' + WIDTH + '×' + h + ' · ' + Math.round(body.length / 1024) + ' KB');
})().catch(e => { console.error(e); process.exit(1); });
