#!/usr/bin/env node
/* dev/cli-glyphs-build.cjs — bake the ASCII glyphs the camera feed draws with into bin/lib/ascii-glyphs.js: each character
   rendered in Consolas bold at the feed's cell size (3 × 6 px, 7 px type), kept as a coverage map (0-255 a pixel, for drawing
   it anti-aliased) and a shape mask (what the feed matches a cell's bright pixels against). The CLI ships no font renderer,
   so the shapes go in as data. Re-run only to change the cell size, the font or the character set. */
'use strict';
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

// usage: node dev/cli-glyphs-build.cjs [cw ch fontPx [out]] (defaults: the feed's own)
const CW = Number(process.argv[2] || 3), CH = Number(process.argv[3] || 6), FS = Number(process.argv[4] || 7), FONT = 'Consolas';
const SHAPES = ".,:;'-_=+*^/|()[]<>~";   // matched against a cell's shape
const DENSE = ' .:-=+*#%@';              // a flat cell, by how bright it is
const OUT = process.argv[5] || path.join(__dirname, '..', 'bin', 'lib', 'ascii-glyphs.js');
const esc = c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c] || c);

(async () => {
  const chars = [...new Set((SHAPES + DENSE).split(''))].filter(c => c !== ' ');
  const glyphs = {};
  for (const c of chars) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${CW}" height="${CH}"><rect width="100%" height="100%" fill="#000"/>` +
      `<text x="${CW / 2}" y="${CH - Math.round(CH * 0.18)}" font-family="${FONT}" font-size="${FS}" font-weight="bold" text-anchor="middle" fill="#fff">${esc(c)}</text></svg>`;
    const { data } = await sharp(Buffer.from(svg)).greyscale().raw().toBuffer({ resolveWithObject: true });
    glyphs[c] = Buffer.from(data).toString('base64');
  }
  const src = '/* bin/lib/ascii-glyphs.js — GENERATED by dev/cli-glyphs-build.cjs: ASCII glyphs as ' + CW + ' x ' + CH + ' coverage maps (' + FONT + ' bold ' + FS + 'px).\n' +
    '   Each value: base64 of ' + (CW * CH) + ' bytes, row by row, 0 = empty, 255 = full ink. Do not edit by hand. */\n' +
    "'use strict';\nmodule.exports = {\n  cw: " + CW + ',\n  ch: ' + CH + ',\n  shapes: ' + JSON.stringify(SHAPES) + ',\n  dense: ' + JSON.stringify(DENSE) + ',\n  glyphs: ' + JSON.stringify(glyphs, null, 2).replace(/\n/g, '\n  ') + '\n};\n';
  fs.writeFileSync(OUT, src);
  console.log('wrote', path.relative(process.cwd(), OUT), chars.length, 'glyphs');
})().catch(e => { console.error(e.message || e); process.exit(1); });
